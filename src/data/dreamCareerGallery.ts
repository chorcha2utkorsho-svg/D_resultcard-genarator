export function matchCareerPresets(careerText?: string): CareerVisionPreset[] {
  const clean = (careerText || '').trim().toLowerCase();
  if (!clean) return DREAM_CAREER_PRESETS;

  const scored = DREAM_CAREER_PRESETS.map((preset) => {
    let score = 0;
    if (clean.includes('ইঞ্জিনিয়ার') || clean.includes('প্রকৌশলী') || clean.includes('engineer')) {
      if (preset.shortLabelBn === 'ইঞ্জিনিয়ার') score += 10;
    }
    if (clean.includes('ডাক্তার') || clean.includes('চিকিৎসক') || clean.includes('doctor')) {
      if (preset.shortLabelBn === 'ডাক্তার') score += 10;
    }
    if (clean.includes('সফটওয়্যার') || clean.includes('বিজ্ঞানী') || clean.includes('কোড') || clean.includes('scientist')) {
      if (preset.shortLabelBn === 'বিজ্ঞানী ও প্রযুক্তিবিদ') score += 10;
    }
    if (clean.includes('পাইলট') || clean.includes('বৈমানিক') || clean.includes('pilot')) {
      if (preset.shortLabelBn === 'পাইলট') score += 10;
    }
    if (clean.includes('শিক্ষক') || clean.includes('গবেষক') || clean.includes('teacher') || clean.includes('অধ্যাপক')) {
      if (preset.shortLabelBn === 'শিক্ষক ও গবেষক') score += 10;
    }
    if (clean.includes('বিসিএস') || clean.includes('প্রশাসক') || clean.includes('ম্যাজিস্ট্রেট')) {
      if (preset.shortLabelBn === 'বিসিএস ও প্রশাসক') score += 10;
    }
    if (preset.careerTag.toLowerCase() === clean) score += 20;
    return { preset, score };
  });

  scored.sort((a, b) => b.score - a.score);
  return scored.map((s) => s.preset);
}
